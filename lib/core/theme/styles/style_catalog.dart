/// I colori di ogni stile (Material You li prende dalla palette scelta).
ColorScheme styleScheme(StyleId id) => switch (id) {
  StyleId.material => throw ArgumentError('Material You usa la palette'),
  StyleId.glass => _glassScheme,
  StyleId.fluent => _fluentScheme,
  StyleId.cartoon => _cartoonScheme,
  StyleId.swiss => _swissScheme,
  StyleId.brutal => _brutalScheme,
  StyleId.gameboy => _gameboyScheme,
  StyleId.clay => _clayScheme,
  StyleId.cyber => _cyberScheme,
  StyleId.sport => _sportScheme,
  StyleId.zen => _zenScheme,
  StyleId.kanji => _kanjiScheme,
};

ColorScheme _from(Color seed, Brightness b) =>
    ColorScheme.fromSeed(seedColor: seed, brightness: b);

